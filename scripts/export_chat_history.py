#!/usr/bin/env python3
"""Export a Claude Code session transcript (.jsonl) to a readable Markdown chat history.

Usage: python3 scripts/export_chat_history.py <transcript.jsonl> [output.md]

Included : every user prompt (verbatim) and every assistant reply (full text, in order).
           Tool calls are listed as one compact line each (tool + target/description).
Omitted  : the model's hidden reasoning (not part of the visible conversation), raw tool outputs,
           and <system-reminder> blocks injected by the harness (CLAUDE.md copies, attachments metadata).
"""
import json
import re
import sys
from datetime import datetime

SYSTEM_REMINDER = re.compile(r"<system-reminder>.*?</system-reminder>", re.DOTALL)


def load(path):
    with open(path, encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def prompt_text(row):
    """Return (text, image_count) for a real user prompt, or None for tool results / meta rows."""
    if row.get("type") != "user" or row.get("isMeta") or "promptId" not in row:
        return None
    content = row["message"]["content"]
    if isinstance(content, str):
        return SYSTEM_REMINDER.sub("", content).strip(), 0
    kinds = {b.get("type") for b in content}
    if "tool_result" in kinds:
        return None
    text = "\n".join(b.get("text", "") for b in content if b.get("type") == "text")
    return SYSTEM_REMINDER.sub("", text).strip(), sum(1 for b in content if b.get("type") == "image")


def tool_line(block):
    name, args = block.get("name", "?"), block.get("input", {}) or {}
    if name == "Bash":
        first = (args.get("command", "").strip().splitlines() or [""])[0][:110]
        what = args.get("description") or first
        return f"`Bash`: {what}"
    if name in ("Write", "Edit", "Read"):
        return f"`{name}`: `{args.get('file_path', '')}`"
    if name == "Artifact":
        return "`Artifact`"
    return f"`{name}`"


def fence(text):
    ticks = "~~~~"
    while ticks in text:
        ticks += "~"
    return f"{ticks}text\n{text}\n{ticks}"


def stamp(row):
    ts = row.get("timestamp", "")
    try:
        return datetime.fromisoformat(ts.replace("Z", "+00:00")).strftime("%Y-%m-%d %H:%M UTC")
    except ValueError:
        return ts


def main():
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else "docs/CHAT_HISTORY.md"
    rows = load(src)

    turns = []  # each: {"prompt": (text, images), "ts": str, "items": [("text"|"tool", str)]}
    for row in rows:
        p = prompt_text(row)
        if p is not None:
            turns.append({"prompt": p, "ts": stamp(row), "items": []})
        elif row.get("type") == "assistant" and turns:
            for block in row["message"]["content"]:
                if block.get("type") == "text" and block["text"].strip():
                    turns[-1]["items"].append(("text", block["text"].strip()))
                elif block.get("type") == "tool_use":
                    turns[-1]["items"].append(("tool", tool_line(block)))

    models = sorted({r["message"].get("model", "") for r in rows if r.get("type") == "assistant"} - {""})
    session = next((r.get("sessionId") for r in rows if r.get("sessionId")), "")
    lines = [
        "# AI chat history: KEYMART (Eneba Intern Assignment 2027)",
        "",
        "Complete conversation between the author and the coding agent (Claude Code), exported from the session transcript.",
        "",
        f"- Session: `{session}`",
        f"- Model(s) recorded: {', '.join(f'`{m}`' for m in models) or 'n/a'}",
        f"- Prompts: {len(turns)} (`P1` to `P{len(turns)}` in this file; the per-task summaries live in `docs/ai-log/`)",
        "- **Prompts are verbatim.** Agent replies are the full visible text, in order. Tool calls (commands run, files written)"
        " appear as compact *Tool call* lines between the replies.",
        "- Not included: the model's hidden reasoning, raw tool outputs, and harness-injected `<system-reminder>` blocks."
        " Screenshots attached to prompts are noted as `[N image(s) attached]`.",
        "- Generated by `scripts/export_chat_history.py`. The final reply of the last prompt is written after the export;"
        " re-run the script after the session to include it.",
        "",
        "---",
        "",
    ]
    for n, turn in enumerate(turns, 1):
        text, images = turn["prompt"]
        lines += [f"## Prompt {n}  ·  {turn['ts']}", ""]
        if images:
            lines += [f"*[{images} image(s) attached]*", ""]
        lines += [fence(text), "", f"### Response {n}", ""]
        previous = None
        for kind, value in turn["items"]:
            if kind == "tool":
                lines.append(f"- *Tool call* {value}")
            else:
                if previous == "tool":
                    lines.append("")
                lines += [value, ""]
            previous = kind
        if previous == "tool":
            lines.append("")
        lines += ["---", ""]

    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {out}: {len(turns)} prompts, {sum(len(t['items']) for t in turns)} reply/tool items")


if __name__ == "__main__":
    main()
